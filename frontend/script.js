// ======================================
// CHANGE WEBSITE LANGUAGE
// ======================================

const languageSelect = document.getElementById("language");

function changeLanguage() {

    const lang = languageSelect.value;
    const t = translations[lang];

    document.querySelector("header p").textContent = t.tagline;

    const navLinks = document.querySelectorAll("nav a");

    const navTexts = [
        t.home,
        t.services,
        t.schemes,
        t.transport,
        t.healthcare
    ];

    navLinks.forEach((link, index) => {
        if (navTexts[index]) {
            link.textContent = navTexts[index];
        }
    });

    document.querySelector("#home h2").textContent = t.welcome;
    document.querySelector("#home p").textContent = t.intro;
    document.querySelector('label[for="language"]').textContent = t.choose;

    document.getElementById("speakButton").textContent = t.read;
    document.getElementById("stopButton").textContent = t.stop;

    document.querySelector("#services h2").textContent = t.explore;
    document.querySelector("#services > p").textContent = t.serviceIntro;

    // Government Schemes Card
    const cards = document.querySelectorAll(".service-card");

    const cardData = [
        [t.schemes, t.schemeDesc, t.schemeBtn],
        [t.transport, t.busDesc, t.busBtn],
        [t.healthcare, t.healthDesc, t.healthBtn],
        [t.emergency, t.emergencyDesc, t.emergencyBtn]
    ];

    cards.forEach((card, index) => {

        card.querySelector("h3").textContent = cardData[index][0];
        card.querySelector("p").textContent = cardData[index][1];
        card.querySelector("a").textContent = cardData[index][2];

    });

    document.querySelector("#schemes h2").textContent = t.schemes;
    document.querySelector("#schemes p").textContent = t.schemeSection;

    document.querySelector("#transport h2").textContent = t.transport;
    document.querySelector("#transport p").textContent = t.busSection;

    document.querySelector("#healthcare h2").textContent = t.healthcare;
    document.querySelector("#healthcare p").textContent = t.healthSection;

    document.querySelector("#emergency h2").textContent = t.emergency;
    document.querySelector("#emergency p").textContent = t.emergencySection;
    document.querySelector("#emergency p:last-child").textContent = t.emergencyNumber;

    document.querySelector("footer p:last-child").textContent = t.footer;

    document.documentElement.lang = lang;
}

languageSelect.addEventListener("change", changeLanguage);


// ======================================
// VOICE ASSISTANCE
// ======================================

const speakButton = document.getElementById("speakButton");
const stopButton = document.getElementById("stopButton");

speakButton.addEventListener("click", function () {

    if (!("speechSynthesis" in window)) {
        alert("Voice assistance is not supported in this browser.");
        return;
    }

    window.speechSynthesis.cancel();

    const lang = languageSelect.value;

    const pageText = document.querySelector("main").innerText;

    const speech = new SpeechSynthesisUtterance(pageText);

    const voiceLanguages = {
        en: "en-IN",
        kn: "kn-IN",
        hi: "hi-IN"
    };

    speech.lang = voiceLanguages[lang];

    window.speechSynthesis.speak(speech);

});


// ======================================
// STOP VOICE ASSISTANCE
// ======================================

stopButton.addEventListener("click", function () {

    window.speechSynthesis.cancel();

});

// ======================================
// GOVERNMENT SCHEMES SEARCH
// ======================================

const schemeSearch = document.getElementById("schemeSearch");

schemeSearch.addEventListener("input", function () {

    const searchText = schemeSearch.value.toLowerCase();

    const schemeCards = document.querySelectorAll(".scheme-card");

    schemeCards.forEach(function (card) {

        const schemeName = card.textContent.toLowerCase();

        if (schemeName.includes(searchText)) {
            card.style.display = "block";
        } else {
            card.style.display = "none";
        }

    });

});
